package compiler

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"path"
	"slices"
	"strings"
)

// Valid values for settings that are written into Cargo.toml. Every value is
// checked against an allowlist so user input can never inject TOML.
var (
	validEditions = []string{"2015", "2018", "2021", "2024"}
	validProfiles = []string{ProfileRelease, ProfileDebug}
	validOpt      = []string{"", "0", "1", "2", "3", "s", "z"}
	validPanic    = []string{"", "unwind", "abort"}
	validKinds    = []Kind{KindProgram, KindLibrary}
)

// Build profiles.
const (
	ProfileRelease = "release"
	ProfileDebug   = "debug"
)

// DefaultEdition is the edition used when none is configured. Edition 2024
// rejects bare #[no_mangle], which most existing snippets use.
const DefaultEdition = "2021"

func (r *Request) validate() error {
	if len(r.Sources) == 0 {
		return fmt.Errorf("compiler: no source files")
	}
	root := r.rootFile()
	if r.Sources[0].Path != root {
		return fmt.Errorf("compiler: first source must be %s, got %q", root, r.Sources[0].Path)
	}
	seen := map[string]bool{}
	for _, s := range r.Sources {
		clean := path.Clean(s.Path)
		if clean != s.Path || path.IsAbs(clean) || strings.HasPrefix(clean, "..") ||
			!strings.HasSuffix(clean, ".rs") || strings.ContainsAny(clean, `\:`) {
			return fmt.Errorf("compiler: invalid source path %q", s.Path)
		}
		if seen[clean] {
			return fmt.Errorf("compiler: duplicate source path %q", s.Path)
		}
		seen[clean] = true
	}
	if !slices.Contains(validKinds, r.Kind) {
		return fmt.Errorf("compiler: invalid artifact kind %q", r.Kind)
	}
	if r.Target == "" || strings.ContainsAny(r.Target, " \t\n\"'\\/") {
		return fmt.Errorf("compiler: invalid target %q", r.Target)
	}
	if !slices.Contains(validEditions, r.edition()) {
		return fmt.Errorf("compiler: invalid edition %q (want one of %v)", r.Edition, validEditions)
	}
	if !slices.Contains(validProfiles, r.profile()) {
		return fmt.Errorf("compiler: invalid profile %q (want %q or %q)", r.Profile, ProfileRelease, ProfileDebug)
	}
	if !slices.Contains(validOpt, r.OptLevel) {
		return fmt.Errorf("compiler: invalid opt-level %q (want one of 0, 1, 2, 3, s, z)", r.OptLevel)
	}
	if !slices.Contains(validPanic, r.Panic) {
		return fmt.Errorf("compiler: invalid panic strategy %q", r.Panic)
	}
	names := map[string]bool{}
	for _, d := range r.Dependencies {
		if err := d.Validate(); err != nil {
			return fmt.Errorf("compiler: %w", err)
		}
		if names[d.Name] {
			return fmt.Errorf("compiler: duplicate dependency %q", d.Name)
		}
		names[d.Name] = true
	}
	return nil
}

func (r *Request) rootFile() string {
	if r.Kind == KindLibrary {
		return "lib.rs"
	}
	return "main.rs"
}

func (r *Request) edition() string {
	if r.Edition == "" {
		return DefaultEdition
	}
	return r.Edition
}

func (r *Request) profile() string {
	if r.Profile == "" {
		return ProfileRelease
	}
	return r.Profile
}

// packageName derives a unique, valid crate name from the sources so that
// artifacts of different builds never collide in a shared target directory.
func (r *Request) packageName() string {
	h := sha256.New()
	fmt.Fprintf(h, "%s\x00", r.Kind)
	for _, s := range r.Sources {
		fmt.Fprintf(h, "%d:%s\x00%d:", len(s.Path), s.Path, len(s.Content))
		h.Write(s.Content)
	}
	return "fg_" + hex.EncodeToString(h.Sum(nil))[:16]
}

// manifest renders the generated Cargo.toml. All interpolated values have
// been validated against allowlists or are generated hex names.
func (r *Request) manifest() string {
	name := r.packageName()
	var b strings.Builder
	b.WriteString("# Generated by ferrogo. Do not edit.\n")
	fmt.Fprintf(&b, "[package]\nname = %q\nversion = \"0.0.0\"\nedition = %q\npublish = false\n", name, r.edition())
	b.WriteString("autobins = false\nautoexamples = false\nautotests = false\nautobenches = false\n\n")
	if r.Kind == KindLibrary {
		fmt.Fprintf(&b, "[lib]\nname = %q\npath = \"src/lib.rs\"\ncrate-type = [\"cdylib\"]\ntest = false\ndoctest = false\nbench = false\n\n", name)
	} else {
		fmt.Fprintf(&b, "[[bin]]\nname = %q\npath = \"src/main.rs\"\ntest = false\nbench = false\n\n", name)
	}
	b.WriteString("[dependencies]\n")
	b.WriteString(r.dependencySection())
	b.WriteString("\n")
	section := "release"
	if r.profile() == ProfileDebug {
		section = "dev"
	}
	fmt.Fprintf(&b, "[profile.%s]\nincremental = false\n", section)
	if r.OptLevel != "" {
		if r.OptLevel == "s" || r.OptLevel == "z" {
			fmt.Fprintf(&b, "opt-level = %q\n", r.OptLevel)
		} else {
			fmt.Fprintf(&b, "opt-level = %s\n", r.OptLevel)
		}
	}
	if r.Panic != "" {
		fmt.Fprintf(&b, "panic = %q\n", r.Panic)
	}
	// An empty workspace table makes the generated package its own workspace
	// root, so cargo never attaches it to a workspace found in a parent dir.
	b.WriteString("\n[workspace]\n")
	return b.String()
}
